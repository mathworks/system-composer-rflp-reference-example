function ds = scalarInputs(names, time, data)
values = cell(1, numel(names));
for k = 1:numel(names)
    values{k} = data(:, k);
end
ds = vectorInputs(names, time, values);
end

function ds = vectorInputs(names, time, values)
ds = Simulink.SimulationData.Dataset;
for k = 1:numel(names)
    signal = timeseries(values{k}, time, 'Name', names{k});
    ds = ds.addElement(signal, names{k});
end
end

