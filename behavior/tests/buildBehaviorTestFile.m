function suite = initializeSuite(suite, name)
suite.Name = name;
suite.Tags = {'behavior'};
for stray = getTestCases(suite)
    remove(stray);
end
end

function tc = addCase(suite, testType, name, model, stopTime, ...
        inputFile, inputVariable, description)
tc = createTestCase(suite, testType, name);
tc.Tags = {'behavior'};
tc.Description = description;
setProperty(tc, ...
    'Model', model, ...
    'SimulationMode', 'Normal', ...
    'OverrideStopTime', true, ...
    'StopTime', stopTime, ...
    'OverrideModelOutputSettings', true, ...
    'SaveOutput', true, ...
    'SignalLogging', true, ...
    'PlotSignalAfterSimulation', true, ...
    'SaveBaselineRunInTestResult', true, ...
    'SaveInputRunInTestResult', true);

input = addInput(tc, inputFile, 'CreateIterations', false);
input.InputString = inputExpression(model, inputVariable);
end

function expression = inputExpression(model, variable)
if ~bdIsLoaded(model)
    load_system(model);
end
ports = find_system(model, 'SearchDepth', 1, 'BlockType', 'Inport');
numbers = cellfun(@str2double, get_param(ports, 'Port'));
[~, order] = sort(numbers);
names = string(get_param(ports(order), 'Name'));
parts = string(variable) + ".getElement('" + names + "')";
expression = char(strjoin(parts, ','));
end

function addOverrides(tc, values)
ps = addParameterSet(tc, 'Name', 'overrides');
for k = 1:2:numel(values)
    addParameterOverride(ps, values{k}, values{k+1});
end
end

function setCriteria(tc, callback)
criteria = getCustomCriteria(tc);
criteria.Enabled = true;
criteria.Callback = callback;
end

function configureBaseline(tc, proj, baselineDir, filename, capture, specs)
path = fullfile(baselineDir, filename);
if capture
    if isfile(path)
        removeProjectFileIfPresent(proj, path);
        delete(path);
    end
    baseline = captureBaselineCriteria(tc, path, false);
    registerProjectFile(proj, path, 'Design');
else
    assert(isfile(path), ['Missing native baseline %s. Run ' ...
        'updateBehaviorBaselines(true) once to capture it.'], path);
    baseline = addBaselineCriteria(tc, path);
    registerProjectFile(proj, path, 'Design');
end

signalCriteria = getSignalCriteria(baseline);
for k = 1:size(specs, 1)
    name = string(specs{k, 1});
    idx = find(endsWith(string({signalCriteria.BlockPath}), "/" + name), 1);
    assert(~isempty(idx), 'Baseline %s has no signal %s.', filename, name);
    signalCriteria(idx).Enabled = true;
    signalCriteria(idx).AbsTol = specs{k, 2};
    signalCriteria(idx).RelTol = specs{k, 3};
    signalCriteria(idx).LeadingTol = specs{k, 4};
    signalCriteria(idx).LaggingTol = specs{k, 4};
    signalCriteria(idx).InterpMethod = specs{k, 5};
end
end

function registerProjectFile(proj, path, label)
files = proj.Files;
idx = find(string({files.Path}) == string(path), 1);
if isempty(idx)
    relative = char(erase(string(path), string(proj.RootFolder) + filesep));
    projectFile = addFile(proj, relative);
else
    projectFile = files(idx);
end
labels = projectFile.Labels;
hasLabel = any(string({labels.CategoryName}) == "Classification" & ...
    string({labels.Name}) == string(label));
if ~hasLabel
    addLabel(projectFile, 'Classification', label);
end
end

function removeProjectFileIfPresent(proj, path)
files = proj.Files;
idx = find(string({files.Path}) == string(path), 1);
if ~isempty(idx)
    removeFile(proj, files(idx));
end
end

